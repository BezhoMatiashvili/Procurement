def _upload(client: TestClient, name: str, data: bytes, media: str = XLSX) -> str:
    r = client.post("/api/v1/documents", headers=H, files={"file": (name, data, media)})
    assert r.status_code == 201, r.text
    body = r.json()
    deadline = time.time() + 20
    while time.time() < deadline:
        job = client.get(f"/api/v1/jobs/{body['parse_job_id']}", headers=H).json()
        if job["status"] in ("done", "failed"):
            assert job["status"] == "done", job
            break
        time.sleep(0.05)
    return str(body["document"]["id"])


def _template(client: TestClient) -> str:
    return _upload(
        client, "006-BID Template.xlsx", build_boq(blank(), priced=False, stated_total=None)
    )


def _bid(client: TestClient, name: str, **kw: object) -> str:
    return _upload(client, f"{name}.xlsx", build_boq(LINES, **kw))  # type: ignore[arg-type]


def _check(client: TestClient, template: str, bids: list[str], **params: str) -> dict:
    r = client.post(
        "/api/v1/checks/boq",
        headers=H,
        params=params,
        json={"template_document_id": template, "bid_document_ids": bids},
    )
    assert r.status_code == 200, r.text
    return dict(r.json())


