def test_rate_outliers_are_top_level_not_charged_to_the_first_bidder(
    client: TestClient,
) -> None:
    """``checks.boq.main`` does ``comparisons[0].findings.extend(outliers)``. That is a CLI
    convenience; copying it would blame bidder #1 for everyone else's outlier."""
    template = _upload(client, "Template.xlsx", build_boq(LINES, stated_total=None))
    gouged = list(LINES)
    gouged[1] = ("1.2", "Steel works", "t", 4, 2_000.0, 800.0)
    bids = [
        _bid(client, "Company-1"),
        _bid(client, "Company-2"),
        _upload(client, "Company-3.xlsx", build_boq(gouged)),
    ]
    report = _check(client, template, bids)

    assert any(f["rule_id"] == "BOQ.RATE_OUTLIER" for f in report["rate_outliers"])
    for bidder in report["bidders"]:
        assert not any(f["rule_id"] == "BOQ.RATE_OUTLIER" for f in bidder["findings"])
    outlier = next(f for f in report["rate_outliers"] if f["rule_id"] == "BOQ.RATE_OUTLIER")
    assert "Company-3" in outlier["message_en"]


