def test_an_unreadable_bid_is_reported_on_that_bidder_and_the_rest_are_compared(
    client: TestClient, monkeypatch: pytest.MonkeyPatch
) -> None:
    """One bidder's workbook that the reader cannot open is that bidder's finding, in the JSON
    report and in the merged workbook alike - never a failed request for every bidder."""
    from procurement_agent.checks import boq as boq_module

    real_read = boq_module.read_boq

    def read(path: Path, *, name: str | None = None, **limits: object) -> object:
        if name == "Broken Co":
            raise KeyError("a part of the workbook the reader expects is missing")
        return real_read(path, name=name, **limits)

    monkeypatch.setattr(boq_module, "read_boq", read)
    template = _template(client)
    bids = [_bid(client, "Company-1"), _bid(client, "Company-2"), _bid(client, "Broken Co")]
    report = _check(client, template, bids)
    by_name = {b["bidder"]: b for b in report["bidders"]}
    assert [f["rule_id"] for f in by_name["Broken Co"]["findings"]] == ["BOQ.UNREADABLE"]
    assert by_name["Broken Co"]["comparable"] is False
    assert by_name["Company-1"]["comparable"] and by_name["Company-2"]["comparable"]

    r = client.post(
        "/api/v1/checks/boq",
        headers=H,
        params={"format": "xlsx"},
        json={"template_document_id": template, "bid_document_ids": bids},
    )
    assert r.status_code == 200, r.text
    assert "SUMMARY" in load_workbook(io.BytesIO(r.content)).sheetnames


def test_a_bid_in_another_currency_is_not_ranked_and_says_why(client: TestClient) -> None:
    """A bid whose price headers name lari where the template's name dollars is reported, kept
    out of the colours and the ranking, and the reason it is not ranked is its currency."""
    template = _upload(client, "T.xlsx", build_real_boq())
    bids = [
        _upload(client, "Company-1.xlsx", build_real_boq(Bid())),
        _upload(client, "Company-2.xlsx", build_real_boq(Bid(factor=0.9))),
        _upload(client, "Company-3.xlsx", build_real_boq(Bid(factor=0.5, currency="GEL"))),
    ]
    report = _check(client, template, bids)
    by_name = {b["bidder"]: b for b in report["leaderboard"]}
    assert by_name["Company-3"]["colour"] is None
    assert by_name["Company-3"]["rank_basis"] is None
    assert [b["bidder"] for b in report["leaderboard"]][-1] == "Company-3"
    assert (by_name["Company-1"]["colour"], by_name["Company-2"]["colour"]) == ("red", "green")
    notes = {s["reason_en"] for s in report["skipped"] if s["rule_id"] == "BOQ.TOTALS"}
    assert notes == {
        "Company-3: is priced in another currency than the template (see its findings), so it "
        "is not ranked"
    }


def test_the_new_bid_findings_reach_the_report_the_page_and_the_workbook(
    client: TestClient,
) -> None:
    """A negative rate, a discount below the total incl. VAT and a bid in lari, together:
    the API reports each, the BOQ page renders and the merged workbook downloads, with the
    bid in lari present but not coloured."""
    template = _upload(client, "T.xlsx", build_real_boq())
    names = ["Company-1", "Company-2", "Company-3", "Company-4"]
    specs = [
        Bid(),
        Bid(factor=0.9, rates={(CIVIL, "1.3"): -21.5}),
        Bid(factor=0.95, discount=0.05),
        Bid(factor=0.5, currency="GEL"),
    ]
    bids = [
        _upload(client, f"{n}.xlsx", build_real_boq(s)) for n, s in zip(names, specs, strict=True)
    ]
    report = _check(client, template, bids)
    rules = {b["bidder"]: {f["rule_id"] for f in b["findings"]} for b in report["leaderboard"]}
    assert "BOQ.NEGATIVE_RATE" in rules["Company-2"]
    assert "BOQ.DISCOUNT" in rules["Company-3"]
    assert "BOQ.CURRENCY" in rules["Company-4"]
    by_name = {b["bidder"]: b for b in report["leaderboard"]}
    assert by_name["Company-4"]["colour"] is None and by_name["Company-4"]["rank_basis"] is None
    assert by_name["Company-2"]["comparable"] is False

    query = f"template={template}&bids={','.join(bids)}"
    page = client.get(f"/ui/checks/boq?{query}", headers=H)
    assert page.status_code == 200, page.text
    for rule in ("BOQ.NEGATIVE_RATE", "BOQ.DISCOUNT", "BOQ.CURRENCY"):
        assert rule in page.text
    r = client.get(f"/ui/checks/boq/merged.xlsx?{query}", headers=H)
    assert r.status_code == 200
    wb = load_workbook(io.BytesIO(r.content))
    assert "SUMMARY" in wb.sheetnames
    cells = [str(c.value) for ws in wb.worksheets for row in ws.iter_rows() for c in row]
    assert any("EXCLUDED: a negative rate" in v for v in cells)
    assert any("Company-4" in v for v in cells)


