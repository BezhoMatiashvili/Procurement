def _compare_run(client: TestClient, case: str = "amount") -> tuple[str, str]:
    left = _upload(client, "base.docx", (COMPARE_PAIRS / "base.docx").read_bytes(), DOCX)
    right = _upload(client, f"{case}.docx", (COMPARE_PAIRS / f"{case}.docx").read_bytes(), DOCX)
    return left, right


