def _make_ui_client(tmp_path: Path, **overrides: object) -> Iterator[TestClient]:
    """The signed-in UI client. Factored out so a test can turn a setting off and look."""
    settings = Settings(
        env="dev",
        data_dir=tmp_path / "data",
        dev_api_key=KEY,
        ollama_base_url="http://127.0.0.1:1",
        retention_days=1,
        **overrides,  # type: ignore[arg-type]
    )
    get_settings.cache_clear()
    app = create_app(settings)
    app.dependency_overrides[get_settings] = lambda: settings
    with TestClient(app) as c:
        c.post("/ui/login", data={"api_key": KEY}, headers=SAME_ORIGIN)
        yield c
    dbmod._engine = None
    dbmod._SessionLocal = None
    get_settings.cache_clear()


@pytest.fixture
def client(tmp_path: Path) -> Iterator[TestClient]:
    yield from _make_ui_client(tmp_path)


def _upload(client: TestClient, name: str, data: bytes, media: str) -> str:
    r = client.post("/api/v1/documents", headers=H, files={"file": (name, data, media)})
    assert r.status_code == 201, r.text
    body = r.json()
    deadline = time.time() + 30
    while time.time() < deadline:
        job = client.get(f"/api/v1/jobs/{body['parse_job_id']}", headers=H).json()
        if job["status"] in ("done", "failed"):
            assert job["status"] == "done", job
            break
        time.sleep(0.05)
    return str(body["document"]["id"])


def _act(client: TestClient) -> str:
    return _upload(client, "act.docx", (FIXTURES / "contract_ka.docx").read_bytes(), DOCX)


def _boq_run(client: TestClient, n: int = 2) -> tuple[str, list[str]]:
    template = _upload(
        client, "Template.xlsx", build_boq(blank(), priced=False, stated_total=None), XLSX
    )
    bids = [
        _upload(client, f"Company-{i}.xlsx", build_boq(LINES, stated_total=1000.0 + i), XLSX)
        for i in range(1, n + 1)
    ]
    return template, bids


